#!/usr/bin/env python3
"""Pack symbolically prepared Block-LU task arrays into BLU_SD1 format.

All array files are raw little-endian uint32 (.u32) or float32 (.f32). The
manifest is intentionally dependency-free JSON so it can be generated by the
existing CPU symbolic stage without NumPy on the host.
"""
import argparse, json, math, struct
from pathlib import Path

MAGIC=b"BLU_SD1\0"; VERSION=1; MAX_ARGS=16; ALIGN=64
SLOTS={
 "GETRF":["a_ptr","a_idx","a_val","l_ptr","l_idx","l_val","u_ptr","u_idx","u_val","u_diag_pos"],
 "GESSM":["l_ptr","l_idx","l_val","b_ptr","b_idx","b_val","x_ptr","x_idx","x_val_csc","x_csc_to_csr","x_val_csr","active_cols","work"],
 "TSTRF":["u_col_ptr","u_row_idx","u_csr_val","u_csc_to_csr","u_diag_pos","b_ptr","b_idx","b_val","x_ptr","x_idx","x_val","active_rows","work"],
 "SSSSM":["a_ptr","a_idx","a_val","l_ptr","l_idx","l_val","u_ptr","u_idx","u_val","s_ptr","s_idx","s_val","work","mark"],
}
DTYPE={"u32":("<I",4),"f32":("<f",4),"uint32":("<I",4),"float32":("<f",4)}
# Use explicit 64-byte header: magic, version, task_count, table_off, data_off,
# total_bytes, matrix_n, then eight reserved words.
HDR=struct.Struct("<8s14I")
TASK=struct.Struct("<6I16I16I16I")

def align(x): return (x+ALIGN-1)//ALIGN*ALIGN

def read_array(path, dtype):
    raw=Path(path).read_bytes()
    fmt,size=DTYPE[dtype]
    if len(raw)%size: raise ValueError(f"{path}: byte size not divisible by {size}")
    return raw

def main():
    ap=argparse.ArgumentParser(); ap.add_argument("manifest"); ap.add_argument("-o","--output",required=True)
    ns=ap.parse_args(); mpath=Path(ns.manifest).resolve(); m=json.loads(mpath.read_text())
    tasks=m.get("tasks",[])
    if not tasks: raise SystemExit("manifest has no tasks")
    table_off=64; data_off=align(table_off+TASK.size*len(tasks)); out=bytearray(data_off)
    recs=[]; data=bytearray()
    for ti,t in enumerate(tasks):
        kind=t["kind"].upper()
        if kind not in SLOTS: raise SystemExit(f"task {ti}: bad kind {kind}")
        arrays=t.get("arrays",{}); offsets=[0]*MAX_ARGS; sizes=[0]*MAX_ARGS; elems=[0]*MAX_ARGS
        for slot,name in enumerate(SLOTS[kind]):
            if name not in arrays: raise SystemExit(f"task {ti} {kind}: missing array {name}")
            spec=arrays[name]
            if isinstance(spec,str): path=mpath.parent/spec; dtype="f32" if path.suffix.lower()==".f32" else "u32"
            else: path=mpath.parent/spec["path"]; dtype=spec.get("dtype","f32" if path.suffix.lower()==".f32" else "u32")
            raw=read_array(path,dtype)
            pos=align(data_off+len(data)); data.extend(b"\0"*(pos-(data_off+len(data))))
            offsets[slot]=pos; sizes[slot]=len(raw); elems[slot]=DTYPE[dtype][1]; data.extend(raw)
        eps=float(t.get("pivot_eps",1e-30)); eps_bits=struct.unpack("<I",struct.pack("<f",eps))[0]
        n=int(t.get("n",m.get("n",0))); active=int(t.get("active_count",0))
        if kind=="SSSSM" and "rows" in t: n=int(t["rows"])
        rec=TASK.pack(int({"GETRF":0,"GESSM":1,"TSTRF":2,"SSSSM":3}[kind]),int(t.get("flags",0)),n,active,eps_bits,len(SLOTS[kind]),*offsets,*sizes,*elems)
        recs.append(rec)
    out.extend(b"\0"*(data_off-len(out))); out.extend(data)
    total=len(out)
    hdr=HDR.pack(MAGIC,VERSION,len(tasks),table_off,data_off,total,int(m.get("n",0)),*([0]*8))
    assert len(hdr)==64
    out[0:64]=hdr
    for i,rec in enumerate(recs): out[table_off+i*TASK.size:table_off+(i+1)*TASK.size]=rec
    Path(ns.output).write_bytes(out)
    print(f"wrote {ns.output}: bytes={total} tasks={len(tasks)} data_offset={data_off}")

if __name__=="__main__": main()
